// Writes THIRD_PARTY_LICENSES.md: the licenses of everything Setryx ships
// (server packages in the image, packages bundled into the web app) plus the
// exercise data and fonts. Run after changing dependencies:
//   node scripts/third-party-licenses.mjs
import { existsSync, readFileSync, readdirSync, realpathSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const readJson = (p) => JSON.parse(readFileSync(p, 'utf8'));

/** Finds a package the way Node does: in node_modules folders up from `from`. */
function locate(name, from) {
  for (let dir = from; ; dir = dirname(dir)) {
    const p = join(dir, 'node_modules', name, 'package.json');
    if (existsSync(p)) return p;
    if (dirname(dir) === dir) return null;
  }
}

const found = new Map();
function walk(name, from) {
  const p = locate(name, from);
  if (!p) return;
  const dir = realpathSync(dirname(p));
  if (!dir.includes('/node_modules/')) return; // our own workspaces
  const pkg = readJson(p);
  const key = `${pkg.name}@${pkg.version}`;
  if (found.has(key)) return;
  found.set(key, { pkg, dir });
  for (const dep of Object.keys(pkg.dependencies ?? {})) walk(dep, dir);
}

// What actually ships: the server's runtime dependencies, and what the web
// app bundles (its dependencies, plus the Workbox code in the service worker).
const server = join(root, 'apps/server');
const web = join(root, 'apps/web');
for (const dep of Object.keys(readJson(join(server, 'package.json')).dependencies)) if (!dep.startsWith('@setryx/')) walk(dep, server);
for (const dep of Object.keys(readJson(join(web, 'package.json')).dependencies)) if (!dep.startsWith('@setryx/')) walk(dep, web);
for (const dep of ['workbox-window', 'workbox-core', 'workbox-routing', 'workbox-strategies', 'workbox-precaching', 'workbox-expiration', 'workbox-cacheable-response']) walk(dep, web);

const licenseText = (dir) => {
  const file = readdirSync(dir).find((f) => /^(licen[cs]e|copying)(\.|$)/i.test(f));
  return file ? readFileSync(join(dir, file), 'utf8').trim() : null;
};
const licenseOf = (pkg) => pkg.license ?? pkg.licenses?.map((l) => l.type).join(' OR ') ?? 'UNKNOWN';

const packages = [...found.values()].sort((a, b) => a.pkg.name.localeCompare(b.pkg.name) || a.pkg.version.localeCompare(b.pkg.version));

let out = `# Third-party licenses

Setryx itself is under the MIT License (see \`LICENSE\`). It ships with the
following work by others. This file is generated by
\`scripts/third-party-licenses.mjs\`.

## Exercise library

The exercise data in \`apps/server/seed/exercises.json\`, and the exercise photos
Setryx can download, come from
[free-exercise-db](https://github.com/yuhonas/free-exercise-db) by yuhonas,
which builds on [exercises.json](https://github.com/wrkout/exercises.json).
Both are released into the public domain under
[The Unlicense](https://unlicense.org/).

## Docker image

The image contains the Node.js binary
([MIT License, with the licenses of its bundled components](https://github.com/nodejs/node/blob/main/LICENSE))
and Alpine Linux packages, each under its own license
(see \`/lib/apk/db/installed\` in the image). The server's npm packages in the
image keep their own license files under \`node_modules\`.

## npm packages

| Package | Version | License |
|---|---|---|
${packages.map(({ pkg }) => `| ${pkg.name} | ${pkg.version} | ${licenseOf(pkg)} |`).join('\n')}

## License texts
`;

for (const { pkg, dir } of packages) {
  const text = licenseText(dir);
  out += `\n### ${pkg.name} ${pkg.version}\n\n`;
  out += text ? `\`\`\`\n${text.replaceAll('```', "'''")}\n\`\`\`\n` : `Licensed under ${licenseOf(pkg)}; the package includes no license file.\n`;
}

writeFileSync(join(root, 'THIRD_PARTY_LICENSES.md'), out);
console.log(`Wrote THIRD_PARTY_LICENSES.md with ${packages.length} packages.`);
